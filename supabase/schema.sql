  if v_col is not null and v_col !~ '^#[0-9A-Fa-f]{6}$' then raise exception 'Основной цвет: формат #RRGGBB'; end if;
  if v_col2 is not null and v_col2 !~ '^#[0-9A-Fa-f]{6}$' then raise exception 'Дополнительный цвет: формат #RRGGBB'; end if;
  if v_logo !~ prefix then raise exception 'Логотип не загружен или загружен не через форму'; end if;
  if jsonb_typeof(pl)<>'array' then raise exception 'Некорректный список игроков'; end if;
  for x in select value from jsonb_array_elements(pl) loop
    nk:=btrim(coalesce(x->>'nick','')); rl:=btrim(coalesce(x->>'role','')); pn:=nullif(btrim(coalesce(x->>'name','')),'');
    pc:=upper(btrim(coalesce(x->>'cc',''))); img:=coalesce(x->>'photo',''); is_sub:=coalesce((x->>'sub')::boolean,false);
    pa:=null; pe:=null;
    if nk !~ '^[A-Za-z0-9_]{2,20}$' then raise exception 'Никнейм «%»: 2–20 символов, только латиница, цифры и _',nk; end if;
    if public.cstt_bad(nk) then raise exception 'Никнейм «%» содержит недопустимые слова',nk; end if;
    if lower(nk)=any(nicks) then raise exception 'Никнейм «%» указан дважды',nk; end if;
    nicks:=nicks||lower(nk);
    if rl !~ '^[A-Za-z ]{2,16}$' then raise exception 'Игрок %: укажите игровую роль',nk; end if;
    if pc='' then pc:='EU'; end if;
    if pc !~ '^[A-Z]{2}$' then raise exception 'Игрок %: код страны — две латинские буквы',nk; end if;
    if pn is not null and (pn !~ '^[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё ''’.-]{0,38}$' or public.cstt_bad(pn)) then raise exception 'Игрок %: имя и фамилия — только буквы',nk; end if;
    if nullif(x->>'age','') is not null then
      if (x->>'age') !~ '^[0-9]{1,2}$' or (x->>'age')::int not between 10 and 60 then raise exception 'Игрок %: возраст от 10 до 60',nk; end if;
      pa:=(x->>'age')::int; end if;
    if nullif(x->>'elo','') is not null then
      if (x->>'elo') !~ '^[0-9]{3,4}$' or (x->>'elo')::int not between 100 and 6000 then raise exception 'Игрок %: FACEIT ELO от 100 до 6000',nk; end if;
      pe:=(x->>'elo')::int; end if;
    if img !~ prefix then raise exception 'Игрок %: фотография не загружена',nk; end if;
    if is_sub then subs:=subs+1; else mains:=mains+1; if pe is not null then v_sum:=v_sum+pe; v_cnt:=v_cnt+1; end if; end if;
    clean:=clean||jsonb_build_object('nick',nk,'photo',img,'role',rl,'cc',pc,'name',pn,'age',pa,'elo',pe,'sub',is_sub);
  end loop;
  if mains<>5 then raise exception 'В основном составе должно быть ровно 5 игроков'; end if;
  if subs>3 then raise exception 'Запасных игроков — не больше 3'; end if;
  if nullif(btrim(coalesce(p->>'elo','')),'') is not null then
    if (p->>'elo') !~ '^[0-9]{3,4}$' or (p->>'elo')::int not between 100 and 6000 then raise exception 'AVG ELO от 100 до 6000'; end if;
    v_elo:=(p->>'elo')::int;
  elsif v_cnt=5 then v_elo:=round(v_sum/5.0);
  else raise exception 'Укажите AVG ELO основного состава'; end if;
  if exists(select 1 from teams where lower(name)=lower(v_name) or lower(tag)=lower(v_tag)) then raise exception 'Команда с таким названием или сокращением уже есть на сайте'; end if;
  if exists(select 1 from team_apps where status='pending' and (lower(name)=lower(v_name) or lower(tag)=lower(v_tag))) then raise exception 'Заявка с таким названием или сокращением уже на рассмотрении'; end if;
  insert into team_apps(uid,name,tag,cc,coach,logo,col,col2,elo,about,players,client_key)
    values(me,v_name,v_tag,v_cc,v_coach,v_logo,v_col,v_col2,v_elo,v_about,clean,v_key) returning id into new_id;
  return jsonb_build_object('ok',true,'id',new_id);
end $$;

create or replace function public.approve_team_app(p_id bigint) returns bigint language plpgsql security definer set search_path=public as $$
declare a team_apps%rowtype; tid bigint; x jsonb; pid bigint; ptm bigint;
begin
  if not public.is_admin() then raise exception 'Нет прав администратора'; end if;
  select * into a from team_apps where id=p_id for update;
  if not found then raise exception 'Заявка не найдена'; end if;
  if a.status<>'pending' then raise exception 'Заявка уже обработана'; end if;
  if exists(select 1 from teams where lower(name)=lower(a.name) or lower(tag)=lower(a.tag)) then raise exception 'Команда с таким названием или сокращением уже есть — измените данные заявки'; end if;
  for x in select value from jsonb_array_elements(a.players) loop
    select id,team into pid,ptm from players where lower(nick)=lower(x->>'nick') limit 1;
    if found and ptm is not null then raise exception 'Игрок % уже состоит в другой команде',x->>'nick'; end if;
  end loop;
  insert into teams(name,tag,cc,col,col2,logo,coach,about,elo,pts,ch) values(a.name,a.tag,a.cc,coalesce(a.col,'#445066'),a.col2,a.logo,a.coach,a.about,a.elo,0,0) returning id into tid;
  for x in select value from jsonb_array_elements(a.players) loop
    select id into pid from players where lower(nick)=lower(x->>'nick') limit 1;
    if pid is null then
      insert into players(nick,name,team,cc,role,age,elo,photo,sub,rt,kd,adr,kast,hs,maps)
        values(x->>'nick',x->>'name',tid,x->>'cc',x->>'role',nullif(x->>'age','')::int,nullif(x->>'elo','')::int,x->>'photo',case when (x->>'sub')::boolean then 1 else 0 end,0,0,0,0,0,0);
    else
      update players set team=tid,cc=x->>'cc',role=x->>'role',photo=x->>'photo',name=coalesce(x->>'name',name),age=coalesce(nullif(x->>'age','')::int,age),elo=coalesce(nullif(x->>'elo','')::int,elo),sub=case when (x->>'sub')::boolean then 1 else 0 end where id=pid;
    end if;
  end loop;
  update team_apps set status='approved',team_id=tid,reviewed_at=now(),reviewed_by=auth.uid(),reason=null where id=p_id;
  return tid;
end $$;

create or replace function public.reject_team_app(p_id bigint,p_reason text) returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'Нет прав администратора'; end if;
  if char_length(btrim(coalesce(p_reason,'')))<3 then raise exception 'Укажите причину отклонения'; end if;
  update team_apps set status='rejected',reason=btrim(p_reason),reviewed_at=now(),reviewed_by=auth.uid() where id=p_id and status='pending';
  if not found then raise exception 'Заявка не найдена или уже обработана'; end if;
end $$;

/* ---------- заявки на участие в турнире ---------- */
create table if not exists tour_regs(
  id bigint generated by default as identity primary key,
  tour bigint not null references tournaments(id) on delete cascade,
  team bigint not null references teams(id) on delete cascade,
  uid uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reason text, created_at timestamptz default now(), reviewed_at timestamptz, reviewed_by uuid references auth.users(id) on delete set null);
create unique index if not exists tour_regs_uq on tour_regs(tour,team) where status in ('pending','approved');
alter table tour_regs enable row level security;
drop policy if exists "tr read" on tour_regs; create policy "tr read" on tour_regs for select to authenticated using (uid=auth.uid() or public.is_admin());
drop policy if exists "tr upd" on tour_regs; create policy "tr upd" on tour_regs for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "tr del" on tour_regs; create policy "tr del" on tour_regs for delete to authenticated using (public.is_admin());

create or replace function public.submit_tour_reg(p_tour bigint,p_team bigint,p_rules boolean,p_terms boolean) returns jsonb language plpgsql security definer set search_path=public as $$
declare me uuid:=auth.uid(); o tournaments%rowtype; new_id bigint;
begin
  if me is null then raise exception 'Войдите в аккаунт, чтобы отправить заявку'; end if;
  if not coalesce(p_rules,false) or not coalesce(p_terms,false) then raise exception 'Подтвердите оба пункта: регламент и правила проведения'; end if;
  select * into o from tournaments where id=p_tour;
  if not found then raise exception 'Турнир не найден'; end if;
  if o.s='fin' then raise exception 'Турнир уже завершён'; end if;
  if coalesce(o.reg,1)=0 then raise exception 'Регистрация на этот турнир закрыта'; end if;
  if not exists(select 1 from teams where id=p_team) then raise exception 'Выберите команду из списка'; end if;
  if (select count(*) from tour_regs where uid=me and status='pending')>=10 then raise exception 'Слишком много заявок на рассмотрении'; end if;
  begin
    insert into tour_regs(tour,team,uid) values(p_tour,p_team,me) returning id into new_id;
  exception when unique_violation then
    raise exception 'Эта команда уже подала заявку на этот турнир';
  end;
  return jsonb_build_object('ok',true,'id',new_id);
end $$;

create or replace function public.review_tour_reg(p_id bigint,p_ok boolean,p_reason text) returns void language plpgsql security definer set search_path=public as $$
declare r tour_regs%rowtype;
begin
  if not public.is_admin() then raise exception 'Нет прав администратора'; end if;
  select * into r from tour_regs where id=p_id for update;
  if not found then raise exception 'Заявка не найдена'; end if;
  if r.status<>'pending' then raise exception 'Заявка уже обработана'; end if;
  if p_ok then
    update tour_regs set status='approved',reason=null,reviewed_at=now(),reviewed_by=auth.uid() where id=p_id;
    if not exists(select 1 from tteams where tour=r.tour and team=r.team) then insert into tteams(tour,team) values(r.tour,r.team); end if;
  else
    if char_length(btrim(coalesce(p_reason,'')))<3 then raise exception 'Укажите причину отклонения'; end if;
    update tour_regs set status='rejected',reason=btrim(p_reason),reviewed_at=now(),reviewed_by=auth.uid() where id=p_id;
  end if;
end $$;

