create or replace function public.new_user() returns trigger language plpgsql security definer set search_path=public as $$
declare want text; n text;
begin
  want:=nullif(trim(coalesce(new.raw_user_meta_data->>'nick','')),'');
  n:=coalesce(want,split_part(new.email,'@',1));
  if exists(select 1 from public.profiles where lower(nick)=lower(n)) then
    if want is not null then raise exception 'nick_taken'; end if;
    n:=n||'_'||floor(random()*9000+1000)::int;
  end if;
  insert into public.profiles(id,nick) values(new.id,n) on conflict do nothing;
  return new;
end $$;

/* нельзя менять свой публичный ID; ник 3–24 символа */
create or replace function public.profile_guard() returns trigger language plpgsql as $$
begin
  if tg_op='UPDATE' then new.pid:=old.pid; end if;
  if new.nick is not null and (char_length(trim(new.nick))<3 or char_length(new.nick)>24) then raise exception 'nick_len'; end if;
  if new.bio is not null and char_length(new.bio)>300 then new.bio:=left(new.bio,300); end if;
  return new;
end $$;
drop trigger if exists profile_guard_t on profiles;
create trigger profile_guard_t before insert or update on profiles for each row execute function public.profile_guard();

