/* ---------- проверка текста (те же правила есть в браузере: src/lib/validate.js) ---------- */
create or replace function public.cstt_norm(t text) returns text language sql immutable as $$
  select regexp_replace(translate(lower(coalesce(t,'')),'0134578@$','oieastbas'),'[^a-zа-яё]','','g') $$;
create or replace function public.cstt_bad(t text) returns boolean language sql immutable as $$
  select public.cstt_norm(t) ~ '(fuck|fuk|shit|bitch|cunt|nigg|fagg|retard|whore|slut|nazi|hitler|porn|rapist|pedoph|kkk|хуй|хуе|хуя|хуи|пизд|ебан|ебат|ебал|бляд|блят|мудак|мудил|гандон|пидор|пидар|пидр|залуп|шлюх|дроч|нацист|сучк|сука|ублюд|говн|чурк|хохл)' $$;
create or replace function public.cstt_pii(t text) returns boolean language sql immutable as $$
  select coalesce(t,'') ~* '(@[a-z0-9_.]+|[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}|https?://|www\.|t\.me/|discord\.gg|vk\.com|\+?[0-9][0-9 ().-]{8,}[0-9])' $$;

